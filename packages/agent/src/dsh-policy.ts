import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

const header = '# Generated by Carina for one worker assignment. Do not edit.\n'

const row = (id: string, body: string): string => `- id: ${id}\n${body}`

/**
 * Writes the DSH overlay for one assignment. The approval policy is never
 * interactive here; the sandbox mode and disabled tools carry the authority.
 */
export const writeWorkerPolicyPatch = async (workspaceDir: string, allowedActions: readonly string[]): Promise<string> => {
  const path = join(workspaceDir, '.carina', 'cordis.patch.yml')
  await mkdir(dirname(path), { recursive: true })
  const canRun = allowedActions.includes('run_command')
  const canWrite = allowedActions.includes('write_workspace') || canRun
  const lines = [
    header,
    row('approval', '  config:\n    policy: never\n'),
    row('sandbox-policy', `  config:\n    mode: ${canWrite ? 'workspace-write' : 'read-only'}\n    workspaceRoot: ${workspaceDir}\n`),
    row('tool-web', '  disabled: true\n'),
  ]
  if (!canRun) {
    lines.push(row('tool-bash', '  disabled: true\n'))
    lines.push(row('tool-pwsh', '  disabled: true\n'))
    lines.push(row('tool-jobs', '  disabled: true\n'))
  }
  await writeFile(path, lines.join(''), 'utf8')
  return path
}

/** Router sessions judge events and must not read or modify a workspace. */
export const writeRouterPolicyPatch = async (routerDir: string): Promise<string> => {
  const path = join(routerDir, 'cordis.patch.yml')
  await mkdir(routerDir, { recursive: true })
  const lines = [
    header,
    row('approval', '  config:\n    policy: never\n'),
    row('sandbox-policy', `  config:\n    mode: read-only\n    workspaceRoot: ${routerDir}\n`),
    row('tool-bash', '  disabled: true\n'),
    row('tool-pwsh', '  disabled: true\n'),
    row('tool-jobs', '  disabled: true\n'),
    row('tool-web', '  disabled: true\n'),
    row('tool-subagent', '  disabled: true\n'),
    row('tool-subagent-control', '  disabled: true\n'),
    row('tool-workflow', '  disabled: true\n'),
  ]
  await writeFile(path, lines.join(''), 'utf8')
  return path
}
